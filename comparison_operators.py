#Greater tha (>)
blue_shirts = 20
red_dresses = 15
if blue_shirts > red_dresses:
    #true
    print("Yes, more shirts")
else:
    #false
    print("No, less shirts")

#Greater than or equal to (>=)
camera_1 = 250
camera_2 = 250
if camera_1 >= camera_2:
    print("Yes, more bandwidth")
else:
    print("No, less bandwidth")


#Less than (<)
if red_dresses < blue_shirts:
    print("Yes, less shirts")
else:
    print("No, there's more blue shirts")

#Less than or equal (<=)
jeans = 20
if jeans <= blue_shirts:
    print("Yes, more jeans")
else:
    print("No, there's more shirts")


#Equality by value (== && ===)
bjarne_stroupstrous = 75
guido_van_rossum = 85

if bjarne_stroupstrous == guido_van_rossum:
    print("Yes, they are born the same year")
else:
    print("No, they are not born the same year")

#Not equal operator (!= or <>)
customer_purchase = 150
customer_budget = 2000
if customer_purchase != customer_budget:
    print("You need to buy more items")
else:
    print("You have exhausted your budget")

