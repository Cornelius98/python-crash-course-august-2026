# Integer (int)
age = 25
print(age)

# Float (float)
price = 99.99
print(price)

# String (str)
name = "Cornelius"
print(name)

# Boolean (bool)
is_student = True
print(is_student)

# List (list)
fruits = ["Apple", "Banana", "Orange"]
print(fruits)

# Tuple (tuple)
coordinates = (10, 20, 30)
print(coordinates)

# Set (set)
colors = {"Red", "Green", "Blue"}
print(colors)

# Dictionary (dict)
student = {
    "name": "Cornelius",
    "age": 25,
    "course": "ICT"
}
print(student)

# Range (range)
numbers = range(1, 6)
print(numbers)

# Bytes (bytes)
data = b"Python"
print(data)

# Bytearray (bytearray)
data_array = bytearray(b"Python")
print(data_array)

# Memoryview (memoryview)
data_view = memoryview(b"Python")
print(data_view)

# None (NoneType)
result = None
print(result)
